namespace MeetingRecord.Business.Helpers;

/// <summary>
/// 內建提示詞範本目錄。
///
/// <para>
/// 新使用者拿到的提示詞清單是空的，而提示詞是「AI 轉會議紀錄」的必要輸入
/// （<c>MeetingService.RequestDraftAsync</c> 沒有提示詞就直接拒絕），所以空清單
/// 等於核心功能不能用。這裡提供一組現成範本讓使用者一鍵建立或挑一個新增。
/// </para>
///
/// <para>
/// 純靜態內容：不進資料庫、entity 也不需要 IsBuiltIn 之類的欄位。建進去之後就是
/// 一般的提示詞資料，使用者可自由修改或刪除。
/// </para>
///
/// <para>
/// 每份 <see cref="PromptTemplatePreset.Content"/> 必須遵守的規則（前四條有
/// <c>PromptTemplatePresetsTests</c> 守著）：
/// <list type="number">
/// <item><b>一定要含 <c>{{transcript}}</c></b>。<c>MeetingDraftJobRunner</c> 只做
/// <see cref="PromptVariableHelper.Render"/>，逐字稿只有在範本含這個變數時才會被代入
/// ——漏了它模型完全拿不到逐字稿，而且不會報任何錯。</item>
/// <item>只用 <see cref="PromptVariableHelper.KnownVariables"/> 裡的變數，否則使用者
/// 每次儲存都會被彈未知變數警告。</item>
/// <item>長度要符合 <c>PromptTemplateAdapterModel</c> 的驗證上限。</item>
/// <item><c>{{meetingDate}}</c> 可能被代入空字串（會議沒填日期時），所以要附一句
/// 空值時該怎麼寫的指示，不能裸寫「會議日期：{{meetingDate}}」。</item>
/// <item><b>不要交代輸出語言</b>。<c>MeetingDraftJobRunner</c> 的共用 system prompt
/// 已強制繁體中文台灣用語與「只依逐字稿作答」。</item>
/// <item>輸出格式一律 Markdown（下游有 Markdown／PDF 匯出）；沒有對應內容的段落
/// 要求寫「無」或「未提及」，不要省略標題——省略標題會讓匯出的結構時有時無。</item>
/// </list>
/// </para>
/// </summary>
public static class PromptTemplatePresets
{
    private const string StandardMinutesContent = """
        請根據以下會議逐字稿，整理成一份完整的會議紀錄。

        會議名稱：{{meetingTitle}}
        會議日期：{{meetingDate}}
        （上方欄位若為空白，表示系統未提供，請在輸出中寫「未提供」）

        請依下列格式輸出 Markdown。逐字稿中沒有對應內容的段落請寫「無」，不要省略標題。

        ## 會議資訊
        - 會議名稱：
        - 會議日期：
        - 出席人員：逐字稿中出現的發言者。無法辨識時寫「逐字稿未標示發言者」。

        ## 會議摘要
        以三到五句話說明這場會議談了什麼、得到什麼結果。

        ## 討論事項
        依主題分段，每個主題一個三級標題（標題用主題本身，不要用「議題一」這種編號），
        底下條列該主題的討論重點、不同意見與最後結論。

        ## 決議事項
        逐條列出已達成共識的決定，每條一句話講清楚「決定了什麼」，不要混入還在討論中的事。

        ## 待辦事項
        以表格呈現。負責人或期限逐字稿未提及時填「未指定」。

        | 項目 | 負責人 | 期限 |
        | --- | --- | --- |

        ## 待釐清事項
        列出被提出但沒有結論、需要後續確認的問題。

        撰寫規則：
        - 寒暄、閒聊、重複語句與口頭語不必納入。
        - 語氣模糊的發言（例如「我看看」、「應該可以吧」）歸到待釐清事項，不要當成決議或待辦。

        會議逐字稿：
        {{transcript}}
        """;

    private const string KeyPointsContent = """
        請把以下逐字稿整理成重點條列。

        會議名稱：{{meetingTitle}}
        （上方欄位若為空白，表示系統未提供，輸出時略過即可）

        請依下列格式輸出 Markdown。

        ## 一句話總結
        用一句話說明這份逐字稿的核心內容。

        ## 重點條列
        依逐字稿的敘述順序分段，每段一個三級標題（標題用該段主題，不要用「第一段」這種編號），
        底下以項目符號列出重點，每點一到兩句話。

        ## 關鍵數字與名詞
        條列逐字稿中出現的數字、金額、比例、日期、專有名詞與英文縮寫，各附一句出現時的說明。
        沒有則寫「無」。

        ## 值得注意的發言
        挑出三到五句對理解全文最關鍵的發言，摘要其重點並標明發言者。
        無法辨識發言者時寫「未標示」。

        撰寫規則：
        - 不要加入逐字稿以外的背景知識、評論或建議。
        - 不要拆解成決議或待辦，這份範本只做重點整理。
        - 寒暄、閒聊與重複語句不必納入。

        逐字稿：
        {{transcript}}
        """;

    private const string DecisionsAndTodosContent = """
        請從以下會議逐字稿中，只抽出「決議」與「待辦事項」兩類資訊，其餘討論過程不必整理。

        會議名稱：{{meetingTitle}}
        會議日期：{{meetingDate}}
        （上方欄位若為空白，表示系統未提供，請在輸出中寫「未提供」）

        請依下列格式輸出 Markdown。

        ## 決議事項
        逐條列出會議中確定下來的決定，每條格式為「決議內容（依據：導致這個決定的討論重點）」。
        若逐字稿中沒有任何明確決議，寫「本次會議未做出明確決議」。

        ## 待辦事項
        以表格呈現：

        | 項目 | 負責人 | 期限 | 優先序 |
        | --- | --- | --- | --- |

        - 項目：一句話寫清楚要做什麼，用動詞開頭。
        - 負責人：逐字稿中被指派或自願承擔的人。未指派寫「未指定」。
        - 期限：逐字稿提到的日期或期間。未提到寫「未指定」。
        - 優先序：填高、中或低，依逐字稿中的語氣強度與是否設有期限判斷。

        ## 未完成的討論
        列出被提出但既沒有結論、也沒有指派負責人的事項。沒有則寫「無」。

        撰寫規則：
        - 只寫真的在逐字稿裡出現的決定與承諾。語氣模糊的（例如「我看看」、「再想想」）
          一律歸到未完成的討論。
        - 同一件事被反覆提到時合併成一條，不要重複列。

        會議逐字稿：
        {{transcript}}
        """;

    private const string ClientInterviewContent = """
        請把以下客戶訪談逐字稿整理成訪談紀要。

        訪談名稱：{{meetingTitle}}
        訪談日期：{{meetingDate}}
        （上方欄位若為空白，表示系統未提供，請在輸出中寫「未提供」）

        請依下列格式輸出 Markdown。逐字稿中沒有對應內容的段落請寫「未提及」。

        ## 訪談對象
        公司或單位名稱、與談人職稱、人數。

        ## 現況與背景
        客戶目前的做法、使用的工具、團隊規模與作業流程。

        ## 痛點
        條列客戶明確抱怨或表示困擾的地方，每點附上逐字稿中的依據（摘要客戶說法的重點，
        不必逐字照抄）。依客戶表達的強烈程度由高到低排序。

        ## 需求與期待
        分成「明確要求」與「隱含期待」兩個子項條列。隱含期待指客戶沒有直接要求、
        但從敘述可以判讀出來的需要。

        ## 顧慮與反對意見
        客戶對價格、時程、資訊安全、導入成本、內部推動阻力等提出的疑慮。沒有則寫「無」。

        ## 後續行動
        以表格呈現。負責人或期限未提及時填「未指定」。

        | 項目 | 負責人 | 期限 |
        | --- | --- | --- |

        ## 尚待確認
        需要回頭向客戶確認的問題。

        撰寫規則：
        - 嚴格區分「客戶說的」與「我方說的」，不要把我方的提案或說法寫成客戶的需求。
        - 不要替客戶推論預算或決策權限，逐字稿沒說就寫「未提及」。

        訪談逐字稿：
        {{transcript}}
        """;

    private const string OnePageSummaryContent = """
        請把以下會議逐字稿壓縮成一份一頁以內的摘要。讀者是沒有參加這場會議的主管。

        會議名稱：{{meetingTitle}}
        會議日期：{{meetingDate}}
        （上方欄位若為空白，表示系統未提供，輸出時略過即可）

        請依下列格式輸出 Markdown，全文控制在 500 字以內。

        ## 結論
        兩到三句話講完這場會議的結果。

        ## 三個重點
        只挑三點，每點一句話，依重要性由高到低排序。

        ## 已定案的決定
        條列已經確定、會影響資源、預算或時程的決定。沒有則寫「無」。

        ## 需要主管出手的事
        條列需要主管決策、核准或跨部門協調的事項，每點註明目前卡在哪裡。沒有則寫「無」。

        ## 下一步
        一句話說明接下來會發生什麼、由誰負責。

        撰寫規則：
        - 不要條列細節討論過程，也不要附逐字稿摘錄。
        - 寧可漏掉次要資訊，也不要超過字數。

        會議逐字稿：
        {{transcript}}
        """;

    /// <summary>全部內建範本。順序即畫面上下拉選單的顯示順序，由通用到專用。</summary>
    public static IReadOnlyList<PromptTemplatePreset> All { get; } =
    [
        new(
            "標準會議紀錄",
            "通用會議紀錄。輸出會議資訊、討論事項、決議、待辦與待釐清事項，適合大多數例行會議。",
            StandardMinutesContent),
        new(
            "逐字稿重點條列",
            "只做重點摘要，不拆解決議與待辦。適合演講、教育訓練、產品說明會等以單向說明為主的場合。",
            KeyPointsContent),
        new(
            "決議與待辦事項",
            "只抽出決議與待辦，表格格式固定，方便直接轉成待辦追蹤。",
            DecisionsAndTodosContent),
        new(
            "客戶訪談紀要",
            "客戶訪談與需求訪談專用。整理客戶背景、痛點、需求、顧慮與後續行動，並區分客戶說法與我方說法。",
            ClientInterviewContent),
        new(
            "一頁摘要",
            "壓縮成 500 字以內的摘要，供沒有參加會議的主管快速掌握結論與待決事項。",
            OnePageSummaryContent),
    ];
}

/// <summary>一份內建提示詞範本。</summary>
/// <param name="Name">提示詞名稱，也是冪等判斷的依據（名稱全域唯一）。</param>
/// <param name="Description">用途說明，直接寫進提示詞的描述欄位。</param>
/// <param name="Content">送給模型的指令內容。</param>
public sealed record PromptTemplatePreset(string Name, string Description, string Content);
